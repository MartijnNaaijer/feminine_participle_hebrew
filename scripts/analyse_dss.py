"""Cross-tabulations for the DSS feminine singular participles.

Reads data/dss_fsg_participles.csv (made by scripts/extract_dss.py) and writes data/dss_tables.md.
Only forms whose final letter is preserved (not reconstructed or uncertain) are counted.
Run from the project root:  python scripts/analyse_dss.py
"""
import os

import pandas as pd

from mdtable import to_md

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
d = pd.read_csv(os.path.join(ROOT, "data", "dss_fsg_participles.csv"))
d["weak"] = d.root_class.str.extract(r"(III-y|II-w/y|II-gem)")[0].fillna("other")
d["corpus"] = d.biblical.map({0: "non-biblical", 1: "biblical"})
d["mt_end"] = d.mt_ending.fillna("none").str.split(" | ", regex=False).str[0]

ok = d[(d.last_letter == "ok") & d.ending.isin(["H", "T"]) & (d.state != "c")]
out = []


def table(title, df):
    out.append(f"## {title}\n")
    out.append(to_md(df))
    out.append("\n")


table("1. Preservation of the final letter (all fsg participles)",
      pd.crosstab([d.corpus, d.last_letter], d.ending, margins=True))
table("2. Ending by stem and root class (final letter preserved, absolute state, no suffix)",
      pd.crosstab([ok.stem, ok.vt, ok.weak], [ok.corpus, ok.ending]))

nb = ok[(ok.corpus == "non-biblical") & (ok.weak == "other")]
cols = ["scroll", "fragment", "line", "glyph", "stem", "ending", "line_text"]
table("3. Non-biblical scrolls: ה forms of non-weak roots (all stems)",
      nb[nb.ending == "H"].sort_values(["stem", "scroll"])[cols].reset_index(drop=True))

bib = d[(d.corpus == "biblical") & (d.last_letter == "ok") & d.ending.isin(["H", "T", "Y"])]
table("4. Biblical scrolls: ending compared with the MT parallel",
      pd.crosstab(bib.ending, bib.mt_end, margins=True))
cols_b = ["scroll", "book", "chapter", "verse", "glyph", "stem", "ending", "mt_word", "mt_parse"]
table("5. Biblical scrolls: forms that differ from the MT or have no MT fsg participle parallel",
      bib[(bib.ending != bib.mt_end)][cols_b].reset_index(drop=True))

q = ok[(ok.stem == "qal") & (ok.vt == "ptca") & ~ok.root_class.str.contains("III-y|II-w/y|II-gem")]
table("6. Qal active (non-weak): plene ו after the first radical",
      pd.crosstab([q.corpus, q.ending], q.plene_o, margins=True))

with open(os.path.join(ROOT, "data", "dss_tables.md"), "w", encoding="utf-8") as fh:
    fh.write("# DSS tables: feminine singular participles\n\nGenerated by scripts/analyse_dss.py "
             "from data/dss_fsg_participles.csv. Do not edit by hand.\n\n" + "\n".join(out))
print("written data/dss_tables.md")
