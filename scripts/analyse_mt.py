"""Cross-tabulations for the MT feminine singular participles.

Reads data/mt_fsg_participles.csv (made by scripts/extract_mt.py) and writes
data/mt_tables.md with the tables used in report.md.
Run from the project root:  python scripts/analyse_mt.py
"""
import os

import pandas as pd

from mdtable import to_md

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
d = pd.read_csv(os.path.join(ROOT, "data", "mt_fsg_participles.csv"))

REDUCED = {"shewa", "hatef patah", "hatef segol", "hatef qamets"}


def h_vowel(x):
    if x in REDUCED:
        return "qoṭlā (reduced)"
    if x == "sere":
        return "qoṭelā (ṣere)"
    return x


def t_type(x):
    if x.startswith("segolate:qamets"):
        return "qoṭālet (pausal segolate)"
    if x.startswith("segolate:"):
        return "qoṭelet (segolate)"
    if x.startswith("Ct"):
        return "qoṭalt"
    if x.startswith("Vt"):
        return "-ēt (III-ʾ)"
    return x


absol = d[(d.state == "a") & d.ending.isin(["H", "T"])].copy()
weak = absol.root_class.str.contains(r"III-y|II-w/y$|II-w/y,|II-w/y \(")
# qal active, mišqal qoṭel (holam after first radical), excluding III-y and II-w/y
qal = absol[(absol.stem == "qal") & (absol.vt == "ptca") & (absol.pattern_first_vowel == "holam") & ~weak].copy()
qal["type"] = [h_vowel(s) if e == "H" else t_type(s) for e, s in zip(qal.ending, qal.form_subtype)]

out = []


def table(title, df):
    out.append(f"## {title}\n")
    out.append(to_md(df))
    out.append("\n")


table("1. All stems: ending by stem (absolute state, no suffix)",
      pd.crosstab([absol.stem, absol.vt], absol.ending, margins=True))
table("2. All stems: ending by root class (III-y / II-w/y / II-gem / other)",
      pd.crosstab(absol.root_class.str.extract(r"(III-y|II-w/y|II-gem)")[0].fillna("other"),
                  absol.ending, margins=True))
table("3. Qal qoṭel (no III-y, II-w/y): form type", qal.type.value_counts().to_frame("n"))
table("4. Qal qoṭel: form type by pause", pd.crosstab(qal.type, qal.pause, margins=True))
table("5. Qal qoṭel: form type by role in phrase", pd.crosstab(qal.type, qal.role, margins=True))
table("6. Qal qoṭel: form type by phrase function", pd.crosstab(qal.type, qal.phrase_function, margins=True))
table("7. Qal qoṭel: form type by book group", pd.crosstab(qal.book_group, qal.type, margins=True))
table("8. Qal qoṭel: ending by book group", pd.crosstab(qal.book_group, qal.ending, margins=True))

oth = absol[(absol.stem != "qal") & ~absol.root_class.str.contains(r"III-y|II-w/y|II-gem")].copy()
table("9. Derived stems (no III-y, II-w/y, II-gem): ending by pause",
      pd.crosstab([oth.stem, oth.ending], oth.pause, margins=True))
table("10. Derived stems: ending by phrase function",
      pd.crosstab([oth.stem, oth.ending], oth.phrase_function, margins=True))
table("11. Derived stems: ending by book group",
      pd.crosstab(oth.book_group, [oth.stem, oth.ending]))

cols = ["book", "chapter", "verse", "word", "type", "pause", "role", "phrase_function", "clause_text"]
lst = qal[qal.type.str.startswith(("qoṭlā", "qoṭelā", "qoṭālet"))].sort_values(["type", "pause"])
table("12. List: qal qoṭlā, qoṭelā and qoṭālet forms", lst[cols].reset_index(drop=True))

with open(os.path.join(ROOT, "data", "mt_tables.md"), "w", encoding="utf-8") as fh:
    fh.write("# MT tables: feminine singular participles\n\nGenerated by scripts/analyse_mt.py "
             "from data/mt_fsg_participles.csv. Do not edit by hand.\n\n" + "\n".join(out))
print("written data/mt_tables.md")
