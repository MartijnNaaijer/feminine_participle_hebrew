"""Tables for the MT–SP comparison of feminine singular participles (Genesis–Deuteronomy).

Reads data/sp_fsg_participles.csv (made by scripts/extract_sp.py) and writes data/sp_tables.md.
Run from the project root:  python scripts/analyse_sp.py
"""
import os

import pandas as pd

from mdtable import to_md

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
d = pd.read_csv(os.path.join(ROOT, "data", "sp_fsg_participles.csv"))
aligned = d[d.source.str.startswith("MT+SP")]
out = []


def table(title, df):
    out.append(f"## {title}\n")
    out.append(to_md(df))
    out.append("\n")


table("1. Alignment", d.source.value_counts().to_frame("n"))
table("2. Ending in MT and SP (aligned forms)", pd.crosstab(aligned.mt_ending, aligned.sp_ending, margins=True))
table("3. Ending by stem in the SP (aligned forms)",
      pd.crosstab([aligned.stem, aligned.vt], aligned.sp_ending, margins=True))
cols = ["source", "book", "chapter", "verse", "mt_word", "sp_word", "stem", "mt_ending", "sp_ending", "sp_parse"]
table("4. Aligned forms whose ending differs", aligned[aligned.mt_ending != aligned.sp_ending][cols].reset_index(drop=True))
table("5. Unaligned forms (MT only / SP only)", d[~d.source.str.startswith("MT+SP")][cols].reset_index(drop=True))

with open(os.path.join(ROOT, "data", "sp_tables.md"), "w", encoding="utf-8") as fh:
    fh.write("# SP tables: feminine singular participles (Genesis–Deuteronomy)\n\nGenerated by "
             "scripts/analyse_sp.py from data/sp_fsg_participles.csv. Do not edit by hand.\n\n" + "\n".join(out))
print("written data/sp_tables.md")
